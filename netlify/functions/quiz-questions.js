const { preflight, respond, readJsonFile, pickRandom, clamp, parseQuery } = require("./shared");

exports.handler = async (event) => {
  const cors = preflight(event);
  if (cors) return cors;

  if (event.httpMethod !== "GET") {
    return respond(405, { error: "Method not allowed" });
  }

  try {
    const query = parseQuery(event);
    const count = clamp(parseInt(query.count, 10) || 6, 1, 10);
    const requestedMode = query.mode === "ai" ? "ai" : "curated";
    const curatedQuestions = readJsonFile("quiz-questions.json", []);

    if (!Array.isArray(curatedQuestions) || !curatedQuestions.length) {
      return respond(500, { error: "No quiz questions available" });
    }

    let questions = [];
    let mode = requestedMode;
    let notice = "";

    if (requestedMode === "ai") {
      const aiQuestions = await generateAiQuizQuestions(count);
      if (aiQuestions.length) {
        const curatedFill = pickRandom(
          curatedQuestions.filter((item) => !aiQuestions.some((g) => g.question === item.question)),
          count - aiQuestions.length
        );
        questions = [...aiQuestions, ...curatedFill].slice(0, count);
        notice =
          aiQuestions.length < count
            ? "AI generated part of this quiz. Curated backup questions filled the rest."
            : "This round was generated by the API with validation and source prompts.";
      } else {
        questions = pickRandom(curatedQuestions, count);
        mode = "curated";
        notice = "AI quiz generation was unavailable, so AquaSave served curated questions instead.";
      }
    } else {
      questions = pickRandom(curatedQuestions, count);
      notice = "Curated quiz questions are served by the backend API.";
    }

    return respond(200, { mode, requestedMode, notice, questions });
  } catch (err) {
    console.error("Quiz question error:", err);
    return respond(500, { error: "Unable to load quiz questions" });
  }
};

async function generateAiQuizQuestions(count) {
  if (!process.env.GEMINI_API_KEY) return [];

  const prompt = `Return only valid JSON. Create ${count} multiple-choice water conservation quiz questions as a JSON array. Each item must have keys question, options, answer, source. options must be an array of exactly 4 short answer strings. answer must be an integer 0-3. source must be a short source description. Avoid duplicates and avoid repeating generic facts. No markdown.`;

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1/models/gemini-2.5-flash:generateContent?key=${process.env.GEMINI_API_KEY}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
        }),
      }
    );

    if (!response.ok) return [];

    const data = await response.json();
    const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
    const match = rawText.match(/\[[\s\S]*\]/);
    if (!match) return [];

    const parsed = JSON.parse(match[0]);
    if (!Array.isArray(parsed)) return [];

    return parsed
      .map((item, i) => ({
        id: item.id || `ai-${Date.now()}-${i}`,
        question: String(item.question || "").trim(),
        options: Array.isArray(item.options) ? item.options.map((o) => String(o || "").trim()).slice(0, 4) : [],
        answer: Number(item.answer),
        source: String(item.source || "AI generated via Gemini").trim(),
      }))
      .filter((item) => item.question && item.options.length === 4 && Number.isInteger(item.answer) && item.answer >= 0 && item.answer <= 3)
      .slice(0, count);
  } catch (err) {
    console.error("AI quiz generation error:", err);
    return [];
  }
}
